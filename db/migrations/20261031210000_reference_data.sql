-- Spec 02: reference data, from v1's schema (../fib-om-v2-reference/migrations).
-- Only identifying fields are required; every other text column is nullable.
-- Identity keys are BY DEFAULT so spec 04 can insert legacy ids.

CREATE TABLE clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  full_name text,
  phone text,
  landline text,
  fax text,
  address_shipping text,
  address_billing text,
  abn text,
  acn text,
  label_reorder_text text,
  label_name text,
  label_sub_name text,
  label_address_line1 text,
  label_address_line2 text,
  label_use_part_number boolean NOT NULL DEFAULT false
);

-- One show_* flag per order-item column (v1 data-ddl-updates.sql; spec 03 column list).
CREATE TABLE product_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  show_product_type_code boolean NOT NULL DEFAULT false,
  show_product_type_name boolean NOT NULL DEFAULT false,
  show_product_size_name boolean NOT NULL DEFAULT false,
  show_product_media_code boolean NOT NULL DEFAULT false,
  show_quantity boolean NOT NULL DEFAULT false,
  show_height boolean NOT NULL DEFAULT false,
  show_width boolean NOT NULL DEFAULT false,
  show_depth boolean NOT NULL DEFAULT false,
  show_has_wire_header boolean NOT NULL DEFAULT false,
  show_has_header_frame boolean NOT NULL DEFAULT false,
  show_type boolean NOT NULL DEFAULT false,
  show_number boolean NOT NULL DEFAULT false,
  show_clip_type boolean NOT NULL DEFAULT false,
  show_clip_position boolean NOT NULL DEFAULT false,
  show_has_gasket boolean NOT NULL DEFAULT false,
  show_pockets boolean NOT NULL DEFAULT false,
  show_has_legs boolean NOT NULL DEFAULT false,
  show_wire_mesh boolean NOT NULL DEFAULT false,
  show_has_gate boolean NOT NULL DEFAULT false,
  show_calculated_id boolean NOT NULL DEFAULT false,
  show_wire_sides boolean NOT NULL DEFAULT false,
  show_pleats boolean NOT NULL DEFAULT false,
  show_wire_metres boolean NOT NULL DEFAULT false,
  show_wire_height boolean NOT NULL DEFAULT false,
  show_media_mats boolean NOT NULL DEFAULT false,
  show_gasket boolean NOT NULL DEFAULT false,
  show_drawing_number boolean NOT NULL DEFAULT false,
  show_cut_count boolean NOT NULL DEFAULT false,
  show_sow_count boolean NOT NULL DEFAULT false,
  show_cut_status boolean NOT NULL DEFAULT false,
  show_sow_status boolean NOT NULL DEFAULT false,
  show_frame_status boolean NOT NULL DEFAULT false,
  show_media_status boolean NOT NULL DEFAULT false,
  show_wire_status boolean NOT NULL DEFAULT false,
  show_package_status boolean NOT NULL DEFAULT false,
  show_assemble_status boolean NOT NULL DEFAULT false
);

CREATE TABLE product_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text NOT NULL,
  millimetres_per_pleat integer
);

CREATE TABLE product_sizes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE product_media (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text NOT NULL,
  pleat_spacing integer
);

CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category_id bigint NOT NULL REFERENCES product_categories (id) ON DELETE RESTRICT,
  type_id bigint NOT NULL REFERENCES product_types (id) ON DELETE RESTRICT,
  size_id bigint NOT NULL REFERENCES product_sizes (id) ON DELETE RESTRICT,
  media_id bigint NOT NULL REFERENCES product_media (id) ON DELETE RESTRICT,
  notcher boolean NOT NULL DEFAULT false,
  efficiency text
);
CREATE INDEX products_category_id_idx ON products (category_id);
CREATE INDEX products_type_id_idx ON products (type_id);
CREATE INDEX products_size_id_idx ON products (size_id);
CREATE INDEX products_media_id_idx ON products (media_id);
