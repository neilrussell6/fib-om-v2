-- Spec 02: delivery dockets and orders.
CREATE TYPE order_status AS ENUM ('new', 'complete', 'archived');
CREATE TYPE docket_status AS ENUM ('current', 'archived');

CREATE TABLE delivery_dockets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_client_id bigint NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
  to_client_id bigint NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
  date date NOT NULL DEFAULT current_date,
  status docket_status NOT NULL DEFAULT 'current',
  docket_number text GENERATED ALWAYS AS (lpad(id::text, 6, '0')) STORED
);
CREATE INDEX delivery_dockets_from_client_id_idx ON delivery_dockets (from_client_id);
CREATE INDEX delivery_dockets_to_client_id_idx ON delivery_dockets (to_client_id);

-- No unique constraint on order_number (spec 02: rejected "new data rule").
CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
  order_number text NOT NULL,
  date date NOT NULL DEFAULT current_date,
  due_date date NOT NULL,
  status order_status NOT NULL DEFAULT 'new',
  delivery_docket_id bigint REFERENCES delivery_dockets (id) ON DELETE RESTRICT
);
CREATE INDEX orders_client_id_idx ON orders (client_id);
CREATE INDEX orders_delivery_docket_id_idx ON orders (delivery_docket_id);
