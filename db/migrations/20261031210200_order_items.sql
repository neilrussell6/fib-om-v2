-- Spec 02: order items. No CHECK constraints on quantities or dimensions.
CREATE TYPE clip_type AS ENUM ('pocket', 'bag', 'hepa', 'gate', 'ring');
CREATE TYPE clip_position AS ENUM ('bevel', 'ludwig', 'clamp');
CREATE TYPE wire_mesh AS ENUM ('0', '1', '2');
CREATE TYPE one_or_two AS ENUM ('1', '2');

CREATE TABLE order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
  product_id bigint NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  part_number text NOT NULL,
  quantity integer NOT NULL,
  height integer NOT NULL,
  width integer NOT NULL,
  depth integer NOT NULL,
  comment text,
  has_wire_header boolean NOT NULL DEFAULT false,
  has_header_frame boolean NOT NULL DEFAULT false,
  type text,
  number integer,
  clip_type clip_type,
  clip_position clip_position,
  has_gasket boolean NOT NULL DEFAULT false,
  pockets integer,
  has_legs boolean NOT NULL DEFAULT false,
  wire_mesh wire_mesh,
  has_gate boolean NOT NULL DEFAULT false,
  wire_sides one_or_two,
  media_mats one_or_two,
  gasket one_or_two,
  drawing_number integer,
  cut_count integer,
  sow_count integer,
  cut_status boolean NOT NULL DEFAULT false,
  sow_status boolean NOT NULL DEFAULT false,
  frame_status boolean NOT NULL DEFAULT false,
  media_status boolean NOT NULL DEFAULT false,
  wire_status boolean NOT NULL DEFAULT false,
  package_status boolean NOT NULL DEFAULT false,
  assemble_status boolean NOT NULL DEFAULT false
);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);
CREATE INDEX order_items_product_id_idx ON order_items (product_id);
